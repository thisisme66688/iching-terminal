let currentToss = 0;
let binaryResult = ""; 
let changingEvents = []; 
let spinCount = 0; // 紀錄已經旋轉了幾圈，確保每次拋擲都能繼續往前轉

const tossBtn = document.getElementById("toss-btn");
const linesContainer = document.getElementById("lines-container");

tossBtn.addEventListener("click", () => {
    if (currentToss >= 6) return;
    
    tossBtn.disabled = true;
    tossBtn.innerText = "🪙 運算中...";
    
    // 1. 預先擲出結果：1 為正面(康熙通寶)，0 為反面(滿文)
    let coin1 = Math.random() > 0.5 ? 1 : 0;
    let coin2 = Math.random() > 0.5 ? 1 : 0;
    let coin3 = Math.random() > 0.5 ? 1 : 0;
    
    // 2. 讓硬幣每次點擊都往前多轉 4 圈 (1440度)
    spinCount += 1440;
    
    // 3. 套用真實翻轉角度：如果是反面(0)，就在落地時多轉 180 度把滿文翻上來
    document.getElementById('c1-inner').style.transform = `rotateX(${spinCount + (coin1 === 0 ? 180 : 0)}deg)`;
    document.getElementById('c2-inner').style.transform = `rotateX(${spinCount + (coin2 === 0 ? 180 : 0)}deg)`;
    document.getElementById('c3-inner').style.transform = `rotateX(${spinCount + (coin3 === 0 ? 180 : 0)}deg)`;

    // 4. 觸發向上拋起的彈跳動畫
    const coins = document.querySelectorAll(".coin");
    coins.forEach(c => c.classList.add("tossing"));
    
    // 5. 0.6秒動畫落地後，結算線條
    setTimeout(() => {
        coins.forEach(c => c.classList.remove("tossing"));
        processTossResult(coin1, coin2, coin3);
    }, 600); 
});

function processTossResult(coin1, coin2, coin3) {
    currentToss++;
    let sum = coin1 + coin2 + coin3;
    
    let isYang = false; 
    let isChanging = false; 
    
    // 3個反面(0) = 老陰(變) / 1正2反(1) = 少陽 / 2正1反(2) = 少陰 / 3個正面(3) = 老陽(變)
    if (sum === 0) { isYang = false; isChanging = true; } 
    if (sum === 1) { isYang = true; isChanging = false; } 
    if (sum === 2) { isYang = false; isChanging = false; } 
    if (sum === 3) { isYang = true; isChanging = true; } 
    
    binaryResult = binaryResult + (isYang ? "1" : "0");
    
    if (isChanging) {
        changingEvents.push(currentToss);
    }
    
    renderYaoLine(isYang, isChanging);
    
    if (currentToss === 6) {
        tossBtn.style.display = "none";
        setTimeout(showFinalResult, 800);
    } else {
        tossBtn.disabled = false;
        tossBtn.innerText = `進行第 ${currentToss + 1} 擲`;
    }
}

function renderYaoLine(isYang, isChanging) {
    if (currentToss === 1) linesContainer.innerHTML = ""; // 清除預設文字
    
    const lineDiv = document.createElement("div");
    lineDiv.className = "yao-line";
    
    // 陽爻是一條直線，陰爻是兩截短線
    if (isYang) {
        lineDiv.innerHTML = `<div class="yang-line ${isChanging ? 'changing' : ''}"></div>`;
    } else {
        lineDiv.innerHTML = `
            <div class="yin-line ${isChanging ? 'changing' : ''}"></div>
            <div class="yin-line ${isChanging ? 'changing' : ''}"></div>
        `;
    }
    
    // prepend 把最新的線加在最上面，達成「由下往上」長出來的效果
    linesContainer.prepend(lineDiv);
}

function showFinalResult() {
    document.getElementById("divination-area").classList.add("hidden");
    const panel = document.getElementById("result-panel");
    panel.classList.remove("hidden");
    
    // 從資料庫找出對應的卦象
    let hexData = hexagramDB.find(h => h.binary === binaryResult);
    
    // 找出這個卦是 64 卦中的第幾卦 (陣列索引從 0 開始，所以要 +1)
    let hexIndex = hexagramDB.indexOf(hexData) + 1;
    
    // 顯示帶有正確數字的卦名
    document.getElementById("hexagram-name").innerText = `【 第 ${hexIndex} 卦：${hexData.name} 】`;
    document.getElementById("conclusion-text").innerText = hexData.conclusion;
    
    // 動態設定進度條寬度 (延遲 0.1 秒讓動畫滑順跑出來)
    setTimeout(() => {
        document.getElementById("bar-success").style.width = hexData.stats.success + "%";
        document.getElementById("text-success").innerText = hexData.stats.success + "%";
        
        document.getElementById("bar-luck").style.width = hexData.stats.luck + "%";
        document.getElementById("text-luck").innerText = hexData.stats.luck + "%";
        
        document.getElementById("bar-risk").style.width = hexData.stats.risk + "%";
        document.getElementById("text-risk").innerText = hexData.stats.risk + "%";
        
        document.getElementById("bar-active").style.width = hexData.stats.active + "%";
        document.getElementById("text-active").innerText = hexData.stats.active + "%";
    }, 100);
    
    // 處理突發變數警告
    if (changingEvents.length > 0) {
        const warningBox = document.getElementById("warning-box");
        const warningList = document.getElementById("warning-list");
        warningBox.classList.remove("hidden");
        
        // 確保清空之前的警告，避免重複疊加
        warningList.innerHTML = ""; 
        
        changingEvents.forEach(stage => {
            const li = document.createElement("li");
            // stage 是 1~6，對應陣列 index 0~5
            li.innerHTML = `<strong>第 ${stage} 階段：</strong> ${hexData.lines[stage - 1]}`;
            warningList.appendChild(li);
        });
    }
}